val LocalBrandColors = staticCompositionLocalOf { LightBrandColors }

/**
 * App theme.
 *
 * @param dynamicColor honours the user's Material You wallpaper palette on
 *   Android 12+; falls back to the brand teal scheme everywhere else.
 */
@Composable
fun LocalNewsTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val supportsDynamic = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
    val context = LocalContext.current

    val colorScheme = when {
        dynamicColor && supportsDynamic && darkTheme -> dynamicDarkColorScheme(context)
        dynamicColor && supportsDynamic -> dynamicLightColorScheme(context)
        darkTheme -> DarkScheme
        else -> LightScheme
    }
    val brandColors = if (darkTheme) DarkBrandColors else LightBrandColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            // Edge-to-edge is enabled in MainActivity; here we only keep the
            // system icon contrast in step with the active theme.
            val window = (view.context as android.app.Activity).window
            WindowCompat.getInsetsController(window, view)
                .isAppearanceLightStatusBars = !darkTheme
            WindowCompat.getInsetsController(window, view)
                .isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(
        LocalBrandColors provides brandColors,
        LocalSpacing provides Spacing(),
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = LocalNewsTypography,
            shapes = LocalNewsShapes,
            content = content,
        )
    }
}

/** `MaterialTheme.spacing.md` — reads naturally next to `MaterialTheme.colorScheme`. */
val MaterialTheme.spacing: Spacing
    @Composable
    @ReadOnlyComposable
    get() = LocalSpacing.current

/** `MaterialTheme.brandColors.success` for the semantic colours M3 doesn't define. */
val MaterialTheme.brandColors: BrandColors
    @Composable
    @ReadOnlyComposable
    get() = LocalBrandColors.current
